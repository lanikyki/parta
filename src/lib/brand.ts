/** Класс ученика или уровень: 1–11, студент, взрослый. */
export const GRADES = [...Array.from({ length: 11 }, (_, i) => String(i + 1)), 'студент', 'взрослый'];

const school = (g: string) => /^\d{1,2}$/.test(g);

/** Только известные значения (защита от мусора в анкетах и запросах). */
export const cleanGrade = (v: unknown) => {
  const g = typeof v === 'string' ? v.trim().toLowerCase() : '';
  return GRADES.includes(g) ? g : '';
};

/** «7 класс», «Студент», «Взрослый» */
export const gradeLabel = (g?: string | null) => (!g ? '' : school(g) ? `${g} класс` : g[0].toUpperCase() + g.slice(1));

/** «для 7 класса», «для студентов», «для взрослых» */
export const gradeFor = (g: string) => (school(g) ? `для ${g} класса` : g === 'студент' ? 'для студентов' : 'для взрослых');

/** Подсказка ИИ, на каком уровне объяснять. */
export const gradeHint = (g: string) =>
  school(g)
    ? `Ученик учится в ${g} классе — объясняй на понятном для этого возраста уровне.`
    : g === 'студент'
      ? 'Ученик — студент колледжа или вуза.'
      : 'Ученик — взрослый человек: объясняй по-взрослому, без школьных примеров.';
