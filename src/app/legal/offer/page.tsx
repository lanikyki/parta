import type { Metadata } from 'next';
import Link from 'next/link';
import { LegalShell } from '@/components/legal/LegalShell';
import { BRAND } from '@/lib/brand';
import { legal } from '@/lib/legal';
import { FREE, PLANS, REF_DISCOUNT, REF_HOLD_DAYS, REF_SHARE, TRIAL_MIN, rub } from '@/lib/plans';

export const metadata: Metadata = { title: 'Публичная оферта' };

// Шаблон договора-оферты для ИП. Перед запуском приёма оплаты покажите текст юристу.
export default function OfferPage() {
  const l = legal();
  const req = [l.name, l.inn && `ИНН ${l.inn}`, l.ogrnip && `ОГРНИП ${l.ogrnip}`].filter(Boolean).join(', ');
  return (
    <LegalShell active="/legal/offer" title="Публичная оферта">
      <p>
        Редакция от {l.updated}. Это предложение (оферта) {req} (далее — Исполнитель) заключить договор об оказании услуг доступа к онлайн-сервису «{BRAND.name}» на условиях
        ниже.
      </p>

      <h2>1. Термины</h2>
      <ul>
        <li>
          <b>Сервис</b> — сайт «{BRAND.name}» и его функции: кабинет, видеоуроки, интерактивная доска, чат и переписка, ИИ-помощник, конспекты и подбор задач.
        </li>
        <li>
          <b>Пользователь</b> — человек, который зарегистрировался в Сервисе: репетитор или ученик.
        </li>
        <li>
          <b>Подписка</b> — платный доступ репетитора к функциям Сервиса по тарифу на оплаченный срок.
        </li>
        <li>
          <b>Бонусы</b> — условные единицы на бонусном счёте Пользователя, которыми можно оплатить подписку (1 бонус = 1 ₽).
        </li>
      </ul>

      <h2>2. Акцепт</h2>
      <p>
        Регистрация в Сервисе означает согласие с этой офертой в части бесплатных функций. Оплата подписки — полное и безоговорочное принятие оферты (акцепт) по ст. 438 ГК РФ.
        Если вы не согласны с условиями, не пользуйтесь Сервисом.
      </p>

      <h2>3. Что входит в услуги</h2>
      <p>Исполнитель предоставляет доступ к Сервису через интернет. Возможности зависят от тарифа:</p>
      <ul>
        <li>
          <b>Бесплатный</b>: {FREE.features.join('; ').toLowerCase()}.
        </li>
        <li>
          <b>«{PLANS.start.name}»</b> — {rub(PLANS.start.price.month)} за 30 дней или {rub(PLANS.start.price.year)} за 365 дней: {PLANS.start.features.join('; ').toLowerCase()}.
        </li>
        <li>
          <b>«{PLANS.pro.name}»</b> — {rub(PLANS.pro.price.month)} за 30 дней или {rub(PLANS.pro.price.year)} за 365 дней: {PLANS.pro.features.join('; ').toLowerCase()}.
        </li>
      </ul>
      <p>
        Ученики пользуются Сервисом бесплатно. Пробный видеоурок ({TRIAL_MIN} минут) предоставляется один раз на аккаунт и номер телефона после подтверждения номера. Актуальные
        цены — на странице <Link href="/pricing">«Тарифы»</Link>. Лимиты ИИ-функций считаются по календарному месяцу (по московскому времени).
      </p>

      <h2>4. Оплата</h2>
      <ul>
        <li>Подписка оплачивается заранее банковской картой или другими способами, которые предлагает платёжный сервис ЮKassa. НДС не облагается, если иное не указано в чеке.</li>
        <li>Срок подписки начинается с момента оплаты. Если подписка уже действует, оплаченный срок добавляется к текущему.</li>
        <li>
          При смене тарифа оставшиеся дни прежнего тарифа пересчитываются по цене нового (например, 20 дней «{PLANS.start.name}» = 10 дней «{PLANS.pro.name}»), а новый срок
          добавляется сверху.
        </li>
        <li>
          <b>Автопродление</b> включается, только если вы поставили отметку при оплате. Тогда за день до окончания срока с сохранённой карты списывается стоимость того же тарифа на
          тот же срок. Отключить автопродление можно в любой момент в разделе «Подписка и баланс» — сохранённая карта при этом удаляется.
        </li>
        <li>Электронный чек приходит на почту, указанную при регистрации.</li>
      </ul>

      <h2 id="refund">5. Отказ от подписки и возврат</h2>
      <p>
        Вы можете отказаться от подписки в любой момент, написав в поддержку. Деньги за неиспользованные полные дни возвращаются на карту, с которой прошла оплата, в течение 10
        рабочих дней. Часть стоимости, оплаченная бонусами, возвращается бонусами. Скидка по приглашению при возврате не компенсируется.
      </p>

      <h2 id="referral">6. Реферальная программа</h2>
      <ul>
        <li>Репетитор получает персональную ссылку для приглашения коллег в разделе «Реферальная программа».</li>
        <li>Коллега, который зарегистрировался по ссылке, получает скидку {Math.round(REF_DISCOUNT * 100)}% на первую оплату подписки.</li>
        <li>
          Пригласившему начисляются бонусы — {Math.round(REF_SHARE * 100)}% от суммы каждой оплаты приглашённого (без учёта оплаченного бонусами). Бонусы становятся доступны через{' '}
          {REF_HOLD_DAYS} дней после оплаты.
        </li>
        <li>Бонусы можно потратить только на подписку в Сервисе. Они не выводятся деньгами, не передаются другим и не возвращаются деньгами.</li>
        <li>Если оплату приглашённого вернули, начисленные за неё бонусы списываются.</li>
        <li>
          Приглашать самого себя нельзя. Если аккаунты связаны (один браузер или устройство, одна карта, один номер телефона), бонусы и скидка не начисляются. При злоупотреблениях
          Исполнитель вправе списать бонусы.
        </li>
        <li>Исполнитель может изменить или завершить программу, предупредив на сайте за 14 дней. Уже доступные бонусы сохраняются.</li>
      </ul>

      <h2>7. Обязанности сторон</h2>
      <p>Исполнитель обеспечивает работу Сервиса, хранит данные Пользователя и помогает через поддержку. Пользователь обязуется:</p>
      <ul>
        <li>указывать достоверные данные и не передавать доступ к аккаунту другим;</li>
        <li>не загружать материалы, которые нарушают закон или чужие права, и не мешать работе Сервиса;</li>
        <li>получать согласие родителей, если занимается с учениками младше 14 лет и они регистрируются в Сервисе.</li>
      </ul>

      <h2>8. Ответственность</h2>
      <p>
        Сервис предоставляется «как есть». Исполнитель старается, чтобы он работал без перерывов, но не отвечает за сбои у интернет-провайдеров, браузеров и сторонних сервисов.
        Плановые работы проводятся по возможности ночью. Если по вине Исполнителя платные функции не работали больше суток подряд, срок подписки продлевается на это время.
      </p>
      <p>
        Ответы ИИ-помощника могут содержать ошибки — это подсказки, а не готовые решения. Ответственность Исполнителя ограничена суммой, уплаченной Пользователем за последний
        оплаченный период.
      </p>

      <h2>9. Персональные данные</h2>
      <p>
        Исполнитель обрабатывает персональные данные по <Link href="/legal/privacy">Политике конфиденциальности</Link>.
      </p>

      <h2>10. Изменение условий и споры</h2>
      <p>
        Исполнитель может менять оферту, публикуя новую редакцию на этой странице. Для уже оплаченного срока действуют условия на дату оплаты. Споры решаются переговорами, а если
        не получится — в суде по закону Российской Федерации.
      </p>

      <h2>11. Реквизиты</h2>
      <p>
        {l.name}
        <br />
        ИНН: {l.inn || '—'}
        <br />
        ОГРНИП: {l.ogrnip || '—'}
        {l.address && (
          <>
            <br />
            Адрес: {l.address}
          </>
        )}
        <br />
        Почта: {l.email ? <a href={`mailto:${l.email}`}>{l.email}</a> : '—'}
        {l.phone && (
          <>
            <br />
            Телефон: {l.phone}
          </>
        )}
      </p>
    </LegalShell>
  );
}
